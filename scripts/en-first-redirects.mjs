import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

async function htmlFiles(root, relative = '') {
  const result = [];
  for (const item of await readdir(join(root, relative), { withFileTypes: true })) {
    const name = relative + item.name;
    if (item.isDirectory()) result.push(...await htmlFiles(root, `${name}/`));
    else if (name.endsWith('.html')) result.push(name);
  }
  return result;
}

const escape = (value) => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');

// Static Astro redirects alone are HTTP 200. Emit a deployable Caddy include and a
// machine-readable map, alongside no-JS fallback pages. Vesper must import the
// include before file_server when releasing; build never edits a running server.
export default function enFirstRedirects(base) {
  const prefix = base === '/' ? '' : base.replace(/\/$/, '');
  return {
    name: 'en-first-redirects',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        const root = fileURLToPath(dir);
        const redirects = {};
        const legacyEnglish = [];
        const fallback = async (from, to) => {
          const filename = join(root, from.replace(/^\//, ''), 'index.html');
          await mkdir(join(filename, '..'), { recursive: true });
          const target = prefix + to;
          const canonical = new URL(target.split('#')[0], 'https://askclaw.dev').href;
          await writeFile(filename, `<!doctype html><html lang="en"><head><meta charset="UTF-8"><meta name="robots" content="noindex"><title>Moved — AskClaw</title><link rel="canonical" href="${escape(canonical)}"><meta http-equiv="refresh" content="0; url=${escape(target)}"></head><body><a href="${escape(target)}">→ ${escape(target)}</a></body></html>\n`);
        };
        for (const file of await htmlFiles(root)) {
          if (!file.endsWith('index.html') || file.startsWith('amber/')) continue;
          const path = '/' + file.slice(0, -'index.html'.length);
          if (!path.startsWith('/zh/')) {
            const old = '/en' + path;
            redirects[old] = path;
            legacyEnglish.push(old);
            await fallback(old, path);
          }
          // Existing model/provider aliases retain their exact final targets,
          // including the single-lane provider's anchor, now with real HTTP 301.
          if (/^\/(?:zh\/)?(?:model|provider)\//.test(path)) {
            const html = await readFile(join(root, file), 'utf8');
            const match = html.match(/<meta http-equiv="refresh" content="0; url=([^"]+)"/);
            if (!match) throw new Error(`Missing alias target: ${path}`);
            redirects[path] = match[1].slice(prefix.length);
          }
        }
        for (const from of ['/method/', '/notes/', '/notes/agent-is-new-software/']) {
          redirects[from] = '/zh' + from;
          await fallback(from, redirects[from]);
        }
        const entries = Object.entries(redirects).sort(([a], [b]) => a.localeCompare(b));
        const manifest = { schema: 'en-first-redirects-v1', base, status: 301,
          legacyEnglish: legacyEnglish.sort(), redirects: Object.fromEntries(entries) };
        await writeFile(join(root, '_en-first-redirects.json'), JSON.stringify(manifest, null, 2) + '\n');
        const lines = ['# Generated by the build. Import inside the site block, before file_server.', '# Must ship with this exact dist; no runtime configuration is changed by the build.'];
        for (const [i, [from, to]] of entries.entries()) {
          const [path, hash] = to.split('#');
          lines.push(`@enfirst${i} path ${prefix}${from} ${prefix}${from.slice(0, -1)} ${prefix}${from}index.html`);
          lines.push(`redir @enfirst${i} ${prefix}${path}{http.request.uri.prefixed_query}${hash ? '#' + hash : ''} 301`);
        }
        // Also strip /en/ on paths added after this inventory; unknown paths still
        // reach the ordinary 404, never a language redirect loop.
        const escapedPrefix = prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        lines.push(`@enfirstRest path_regexp enfirstRest ^${escapedPrefix}/en/(.*)$`);
        lines.push(`redir @enfirstRest ${prefix}/{re.enfirstRest.1}{http.request.uri.prefixed_query} 301`);
        await writeFile(join(root, '_en-first.caddy'), lines.join('\n') + '\n');
      },
    },
  };
}
